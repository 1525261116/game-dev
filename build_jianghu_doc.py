# ---------------------------------------------------------------- 样式与渲染

BODY_FONT = "宋体"
HEAD_FONT = "黑体"


def style_run(run, font=BODY_FONT, size=10.5, bold=False, color=None):
    run.font.name = font
    run.font.size = Pt(size)
    run.font.bold = bold
    if color:
        run.font.color.rgb = color
    run._element.rPr.rFonts.set(qn("w:eastAsia"), font)


def setup_styles(document):
    normal = document.styles["Normal"]
    normal.font.name = BODY_FONT
    normal.font.size = Pt(10.5)
    normal.element.rPr.rFonts.set(qn("w:eastAsia"), BODY_FONT)
    normal.paragraph_format.space_after = Pt(3)
    normal.paragraph_format.line_spacing = 1.25

    for name, size, color in (("Heading 1", 16, RGBColor(0x8B, 0x00, 0x00)),
                              ("Heading 2", 13, RGBColor(0x1F, 0x3A, 0x5F)),
                              ("Heading 3", 11.5, RGBColor(0x33, 0x33, 0x33))):
        st = document.styles[name]
        st.font.name = HEAD_FONT
        st.font.size = Pt(size)
        st.font.bold = True
        st.font.color.rgb = color
        st.element.rPr.rFonts.set(qn("w:eastAsia"), HEAD_FONT)
        st.paragraph_format.space_before = Pt(10 if name == "Heading 1" else 6)
        st.paragraph_format.space_after = Pt(4)


def build(path):
    document = Document()
    setup_styles(document)

    for section in document.sections:
        section.top_margin = Pt(56)
        section.bottom_margin = Pt(56)
        section.left_margin = Pt(64)
        section.right_margin = Pt(64)

    title = document.add_paragraph()
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    style_run(title.add_run("江湖从心　策划案 v0.2"), HEAD_FONT, 22, True,
              RGBColor(0x8B, 0x00, 0x00))
    sub = document.add_paragraph()
    sub.alignment = WD_ALIGN_PARAGRAPH.CENTER
    style_run(sub.add_run("武侠开放世界 · 单机 RPG · 多端"), BODY_FONT, 11,
              False, RGBColor(0x66, 0x66, 0x66))

    for kind, payload in BLOCKS:
        if kind == "h1":
            document.add_heading(payload, level=1)
        elif kind == "h2":
            document.add_heading(payload, level=2)
        elif kind == "h3":
            document.add_heading(payload, level=3)
        elif kind == "p":
            p = document.add_paragraph()
            style_run(p.add_run(payload))
        elif kind == "li":
            p = document.add_paragraph(style="List Bullet")
            p.paragraph_format.space_after = Pt(2)
            style_run(p.add_run(payload))
        elif kind == "tbl":
            rows = payload
            table = document.add_table(rows=0, cols=len(rows[0]))
            table.style = "Table Grid"
            for r_i, row in enumerate(rows):
                cells = table.add_row().cells
                for c_i, text in enumerate(row):
                    cell_p = cells[c_i].paragraphs[0]
                    cell_p.alignment = WD_ALIGN_PARAGRAPH.CENTER
                    style_run(cell_p.add_run(text), BODY_FONT, 10, r_i == 0)
            document.add_paragraph().paragraph_format.space_after = Pt(2)

    document.save(path)
    print("saved:", path)


if __name__ == "__main__":
    build("江湖从心_策划案_v0.2.docx")
